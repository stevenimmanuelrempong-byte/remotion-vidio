// Turns the raw whisper JSON into src/vlog2Words.ts with a few context-based spelling fixes.
// Usage: node scripts/prep-vlog2-words.mjs <whisper.json>
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
const ROOT = path.resolve(import.meta.dirname, "..");
const raw = JSON.parse(readFileSync(process.argv[2], "utf8"));
let words = raw.flatMap((s) => s.words).map((w) => ({ s: w.s, e: w.e, w: w.w.replace(/[.!?]+$/, "") .trim(), p: /[,.!?]$/.test(w.w) }));
const REPLACE = { 3.87: "jadi", 40.17: "bisa", 47.63: "dukun", 62.81: "Opang" };
const MERGE_NEXT = [14.35, 19.83, 37.95, 59.51]; // ke+kayaan, ke+percayaan, usaha+kan, usaha+kan
const out = [];
for (let i = 0; i < words.length; i++) {
  const w = { ...words[i] };
  const key = w.s;
  if (REPLACE[key]) w.w = REPLACE[key];
  if (key === 41.99) w.w = "usaha"; // "umur" -> "usaha"
  if (MERGE_NEXT.includes(key) && words[i + 1]) { w.w = (w.w + words[i + 1].w).replace(/,$/, ""); w.e = words[i + 1].e; w.p = words[i + 1].p; i++; }
  w.w = w.w.replace(/,$/, "");
  out.push(w);
}
writeFileSync(path.join(ROOT, "src/vlog2Words.ts"), `// generated by scripts/prep-vlog2-words.mjs\nexport const VLOG2_WORDS: { s: number; e: number; w: string; p: boolean }[] = ${JSON.stringify(out)};\n`);
